//! 01 (0x) - вычисление `Layout` для массива (раздел 1 README).
//!
//! Прежде чем что-то выделять на куче вручную, нужно описать *что* именно выделяем:
//! сколько байт и с каким выравниванием. Это делает тип `std::alloc::Layout`. Для
//! массива из `n` элементов типа `T` layout строит `Layout::array::<T>(n)`. Он
//! возвращает `Result`, потому что при большом `n` суммарный размер может переполнить
//! допустимый предел (`isize::MAX` байт) - в этом случае возвращается `Err`.
//!
//! Реализуй три функции (unsafe не нужен, всё на уровне типов):
//! - `array_bytes::<T>(n)` -> `Option<usize>`: размер в байтах массива `[T; n]`
//!   (`Layout::array::<T>(n)`, у полученного layout взять `.size()`); при переполнении
//!   вернуть `None`.
//! - `layout_of::<T>(n)` -> `Option<(usize, usize)>`: пара `(size, align)` того же
//!   массива; при переполнении - `None`.
//! - `elem_stride::<T>()` -> `usize`: расстояние в байтах между соседними элементами
//!   массива `T` (это `size_of::<T>()`, уже с учётом выравнивания элемента).
//!
//! Документация: <https://doc.rust-lang.org/std/alloc/struct.Layout.html>
//! (`Layout::array`, методы `size`/`align`).

