//! 03 (1x) - выделить одно значение на куче вручную (раздел 3 README).
//!
//! Полный цикл ручной работы с кучей: `alloc` -> запись -> чтение -> `dealloc`. Здесь -
//! одна ячейка `u64`. Три функции работают в связке.
//!
//! Реализуй:
//! - `alloc_u64(v)` -> `NonNull<u64>` (безопасная сигнатура, но внутри unsafe):
//!   - построй `Layout::new::<u64>()`;
//!   - выдели: `alloc(layout)` (возвращает `*mut u8`), приведи к `*mut u64`;
//!   - если указатель нулевой - вызови `handle_alloc_error(layout)` (не возвращается);
//!     иначе оберни в `NonNull`;
//!   - запиши `v` в свежую память через `.write(v)` (именно `write`, а не `*p = v`:
//!     присваивание сначала пытается уронить старое значение, а его там ещё нет);
//!   - верни `NonNull`.
//! - `unsafe read_u64(p)` -> `u64`: прочитать значение (`p.as_ptr().read()`).
//! - `unsafe free_u64(p)`: освободить ту же ячейку - `dealloc(ptr as *mut u8, layout)`
//!   с тем же `Layout::new::<u64>()`, что был при выделении.
//!
//! Инвариант: `free_u64` вызывается ровно один раз для указателя из `alloc_u64`, и после
//! него указатель использовать нельзя (иначе use-after-free / double-free).
//!
//! Документация: <https://doc.rust-lang.org/std/alloc/index.html>
//! (`alloc`, `dealloc`, `handle_alloc_error`, `Layout`).

