//! 07 (3x) - `reverse!(...)`: TT-muncher с аккумулятором. Эталонное решение.

#[macro_export]
macro_rules! reverse {
    // Публичный вход: запускаем рекурсию с пустым аккумулятором.
    ($($x:expr),* $(,)?) => {
        $crate::reverse!(@acc [] $($x),*)
    };
    // База: ввод опустел - отдать аккумулятор массивом.
    (@acc [$($acc:expr),*]) => {
        [$($acc),*]
    };
    // Шаг: снять голову, положить её ПЕРЕД аккумулятором, продолжить по хвосту.
    (@acc [$($acc:expr),*] $head:expr $(, $tail:expr)*) => {
        $crate::reverse!(@acc [$head $(, $acc)*] $($tail),*)
    };
}
