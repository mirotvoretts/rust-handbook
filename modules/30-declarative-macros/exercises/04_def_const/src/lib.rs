//! 04 (1x) - `def_const!(NAME: ty = expr)`: генерация элемента (разделы 3, 2 README).
//!
//! Напиши макрос `def_const!`, который по описанию генерирует объявление константы:
//!
//! ```ignore
//! def_const!(LIMIT: u32 = 100);   // разворачивается в pub const LIMIT: u32 = 100;
//! def_const!(NAME: &str = "rust");
//! ```
//!
//! Макрос порождает *элемент* (item), а не выражение, поэтому вызывается на уровне модуля.
//!
//! Подсказки:
//! - образец: имя как `$name:ident`, тип как `$ty:ty`, значение как `$val:expr`, между ними
//!   литеральные токены `:` и `=`;
//! - раскрытие - объявление `pub const $name: $ty = $val;` (имя типа гигиеной не защищено,
//!   но здесь всё подставляется из аргументов);
//! - специфаер `ident` матчит идентификатор, `ty` - тип.
//!
//! Заглушка ниже - `compile_error!`: пока макрос не реализован, крейт не компилируется, это
//! ожидаемо. Fragment specifiers:
//! <https://doc.rust-lang.org/reference/macros-by-example.html#metavariables>.

#[macro_export]
macro_rules! def_const {
    ($($t:tt)*) => {
        compile_error!("реализуй макрос def_const (упражнение не решено)");
    };
}
