//! 03 (1x) - `max!(a, b, ...)`: несколько правил и рекурсия (раздел 6 README).
//!
//! Напиши макрос `max!`, возвращающий наибольшее из перечисленных выражений (хотя бы одно).
//! Тип элементов - любой `PartialOrd` (тесты используют целые). Реализация - рекурсивная:
//! - базовое правило: один аргумент `max!(x)` -> сам `x`;
//! - общее правило: голова + непустой хвост -> максимум головы и `max!(хвост)`.
//!
//! Подсказки:
//! - правила пробуются сверху вниз; частный случай (один аргумент) ставь раньше общего;
//! - хвост захватывается как `$($rest:expr),+`, рекурсивный вызов - `max!($($rest),+)`;
//! - экспортированный макрос вызывает себя через полный путь `$crate::max!(...)`;
//! - чтобы не вычислять выражения по нескольку раз, привяжи голову и хвост к `let`.
//!
//! Заглушка выдаёт `compile_error!`, пока макрос не реализован. Рекурсивные макросы:
//! <https://veykril.github.io/tlborm/decl-macros/patterns/tt-muncher.html>.

