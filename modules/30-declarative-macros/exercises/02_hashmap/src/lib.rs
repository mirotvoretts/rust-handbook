//! 02 (0x) - `hashmap!{ k => v, ... }`: синхронное повторение пар (раздел 4 README).
//!
//! Напиши макрос `hashmap!`, собирающий `std::collections::HashMap` из пар
//! `ключ => значение`:
//! - `hashmap!{}` -> пустая карта;
//! - `hashmap!{ "a" => 1, "b" => 2 }` -> карта с этими парами;
//! - хвостовая запятая допускается.
//!
//! Подсказки:
//! - пара захватывается образцом `$k:expr => $v:expr` (токен `=>` в образце - литеральный,
//!   он должен встретиться в вызове дословно);
//! - список пар - повторение `$($k:expr => $v:expr),*`; `$k` и `$v` под одним `$(...)`
//!   разворачиваются синхронно, попарно (например, `m.insert($k, $v);`);
//! - хвостовую запятую разрешает `$(,)?`.
//!
//! Заглушка выдаёт `compile_error!`, пока макрос не реализован, - замени её. Синхронные
//! повторения: <https://doc.rust-lang.org/reference/macros-by-example.html>.

#[macro_export]
macro_rules! hashmap {
    ($($t:tt)*) => {
        compile_error!("реализуй макрос hashmap (упражнение не решено)")
    };
}
