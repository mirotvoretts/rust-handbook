//! 07 (3x) - `reverse!(...)`: TT-muncher с аккумулятором (раздел 6 README).
//!
//! Напиши макрос `reverse!`, который принимает список выражений и разворачивается в
//! *массив* с этими элементами в обратном порядке:
//!
//! ```ignore
//! reverse!(1, 2, 3, 4)  ==  [4, 3, 2, 1]
//! reverse!()            ==  []
//! ```
//!
//! Прямого способа "перевернуть" список в декларативном макросе нет - нужен muncher:
//! внутреннее правило по одному снимает элемент с начала ввода и кладёт его в *начало*
//! аккумулятора, а когда ввод опустел, отдаёт накопленное как массив.
//!
//! Подсказки:
//! - заведи внутренние правила со служебным маркером (например `@acc [...]`), чтобы отличать
//!   их от публичного вызова; публичное правило запускает рекурсию с пустым аккумулятором;
//! - на каждом шаге: `@acc [накопленное] голова, хвост...` -> рекурсия
//!   `@acc [голова, накопленное] хвост...`;
//! - база `@acc [накопленное]` (ввод пуст) -> `[накопленное]`;
//! - рекурсивные вызовы делай через `$crate::reverse!(...)`, элементы бери как `expr`, а
//!   структуру перебирай повторениями.
//!
//! Заглушка выдаёт `compile_error!`, пока макрос не реализован. Паттерн TT muncher:
//! <https://veykril.github.io/tlborm/decl-macros/patterns/tt-muncher.html>.

