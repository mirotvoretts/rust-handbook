//! из стандартной библиотеки, но без оптимизаций):
//! - `my_vec![]` -> пустой `Vec`;
//! - `my_vec![a, b, c]` -> `Vec` с этими элементами по порядку;
//! - хвостовая запятая допускается: `my_vec![a, b,]`.
