//! Подсказки:
//! - список выражений через запятую захватывается повторением `$($x:expr),*`;
//! - необязательную хвостовую запятую разрешает `$(,)?` в конце образца;
//! - тело повторения `$( ... )*` разворачивается по каждому захваченному `$x` (например,
//!   `v.push($x);`).
