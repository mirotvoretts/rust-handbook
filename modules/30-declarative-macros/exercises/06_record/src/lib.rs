//! 06 (2x) - `record!(Name { field: ty, ... })`: генерация структуры (разделы 3, 4 README).
//!
//! Напиши макрос `record!`, который по описанию порождает структуру и конструктор:
//!
//! ```ignore
//! record!(Point { x: i32, y: i32 });
//! // должно развернуться примерно в:
//! //   #[derive(Debug, Clone, PartialEq)]
//! //   pub struct Point { pub x: i32, pub y: i32 }
//! //   impl Point { pub fn new(x: i32, y: i32) -> Self { Point { x, y } } }
//! ```
//!
//! Требования к сгенерированному коду:
//! - структура `pub`, все поля `pub`, с derive `Debug, Clone, PartialEq`;
//! - ассоциированная функция `pub fn new(...)`, принимающая поля в порядке объявления и
//!   возвращающая `Self`.
//!
//! Подсказки:
//! - имя структуры - `$name:ident`; список полей - повторение `$($field:ident : $ty:ty),*`
//!   с опциональной хвостовой запятой;
//! - одни и те же метапеременные `$field`/`$ty` разворачиваются и в объявлении полей, и в
//!   сигнатуре `new`, и в теле конструктора (там достаточно `$name { $($field),* }`).
//!
//! Заглушка - `compile_error!`: пока макрос не реализован, крейт не компилируется. Генерация
//! элементов: <https://veykril.github.io/tlborm/decl-macros/building-blocks/parsing.html>.

