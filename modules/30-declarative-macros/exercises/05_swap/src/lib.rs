//! 05 (2x) - `swap!(a, b)`: обмен значений и гигиена (раздел 5 README).
//!
//! Напиши макрос `swap!`, меняющий местами значения двух изменяемых переменных. Вызов -
//! в позиции оператора: `swap!(x, y);`.
//!
//! ```ignore
//! let mut x = 1;
//! let mut y = 2;
//! swap!(x, y);        // теперь x == 2, y == 1
//! ```
//!
//! Подсказки:
//! - образец - две метапеременные-выражения `$a:expr, $b:expr`;
//! - раскрытие - блок с временной переменной: сохранить `$a`, присвоить `$a = $b`, затем
//!   вернуть сохранённое в `$b`;
//! - здесь важна гигиена: временная переменная из тела макроса не должна конфликтовать с
//!   переменной вызывающего, даже если та названа так же (это проверяет отдельный тест).
//!
//! Заглушка выдаёт `compile_error!`, пока макрос не реализован. Гигиена:
//! <https://veykril.github.io/tlborm/decl-macros/minutiae/hygiene.html>.

#[macro_export]
