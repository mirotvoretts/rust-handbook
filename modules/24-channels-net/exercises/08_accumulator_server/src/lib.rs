//! 08 (3x) - многоклиентный сервер с общим состоянием.
//!
//! Сервер держит общий целочисленный аккумулятор (изначально 0) и обрабатывает
//! соединения параллельно, разделяя аккумулятор через Arc<Mutex<i64>> (M23).
//! Протокол - одна строка-команда на соединение:
//!   "ADD n\n"  - прибавить n к аккумулятору, в ответ прислать новое значение и '\n';
//!   "TOTAL\n"  - прислать текущее значение аккумулятора и '\n', ничего не меняя.
//! Любая другая строка - ответ "ERR\n".
//!
//! Требования к запуску те же, что в 06/07: bind на "127.0.0.1:0", адрес через
//! local_addr, слушающий цикл и обработчики - в фоновых потоках; аккумулятор общий
//! для всех соединений.
//!
//! Подсказки по конструкциям (за пределами теории модуля):
//! - разбор одной строки: BufReader + BufRead::read_line
//!   (см. https://doc.rust-lang.org/std/io/trait.BufRead.html#method.read_line);
//! - отделить префикс команды: str::strip_prefix
//!   (см. https://doc.rust-lang.org/std/primitive.str.html#method.strip_prefix);
//! - TcpStream::try_clone, str::parse, writeln! - как в упражнении 07.

