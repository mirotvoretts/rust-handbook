//! 06 (2x) - гашение паники на границе FFI (раздел 6 README).
//!
//! Паника Rust разворачивает стек; сквозь кадры C это делать нельзя. С Rust 1.81 паника
//! через `extern "C"` по умолчанию завершает процесс (`abort`). Правильно - поймать её в
//! своей экспортированной функции и вернуть C код ошибки. Инструмент - `catch_unwind`:
//! выполняет замыкание и отдаёт `Err`, если внутри была паника.
//!
//! Функция `divide` (дана) паникует на делении на ноль. Реализуй `checked_div` так, чтобы
//! паника наружу не выходила:
//! - обернуть вызов `divide(a, b)` в `catch_unwind`. Замыкание нужно завернуть в
//!   `std::panic::AssertUnwindSafe`, иначе не пройдёт bound `UnwindSafe`.
//! - при `Ok(v)`: записать `v` в `*out` (если `out` не null) и вернуть 0.
//! - при `Err(_)`: вернуть 1, ничего не записывая.
//!
//! (Сообщение паники при этом всё равно печатается в stderr - это нормально, процесс не
//! падает.)
//!
//! `catch_unwind`: <https://doc.rust-lang.org/std/panic/fn.catch_unwind.html>. Про
//! раскрутку стека: <https://doc.rust-lang.org/nomicon/unwinding.html>.

use std::os::raw::c_int;

/// Внутренняя Rust-логика: паникует на делении на ноль (менять не нужно).
fn divide(a: i32, b: i32) -> i32 {
    if b == 0 {
        panic!("division by zero");
    }
    a / b
}

