//! 02 (0x) - `#[repr(C)] union` и type punning (раздел 7 README).
//!
//! В union все поля лежат по одному адресу, наложенные друг на друга. Тега активного
//! варианта нет, поэтому чтение поля - `unsafe`: компилятор не знает, что было записано.
//! Здесь все три поля - 4 байта и валидны для любого набора бит, значит перечитывать их
//! друг через друга (type punning) безопасно.
//!
//! Тип `Bits32` уже объявлен. Реализуй:
//! - `from_u32(x)` / `from_f32(x)` - собрать `Bits32`, записав соответствующее поле.
//! - `as_u32(b)` - прочитать байты как `u32`.
//! - `as_f32(b)` - прочитать те же байты как `f32`.
//! - `as_ne_bytes(b)` - прочитать их как массив `[u8; 4]` (в порядке байт этой платформы).
//!
//! Чтение поля union делается из `unsafe`-блока (например `b.u`). Аксессоры при этом
//! безопасны для вызывающего, так как любой набор из 4 байт валиден для всех трёх полей.
//!
//! Справка по union: <https://doc.rust-lang.org/reference/items/unions.html>.

