//! 02 (1x) - impl Trait в возвращаемой позиции.
//!
//! Тип замыкания невыразим - вернуть его можно только как `-> impl Fn(...)`.
//! Обратите внимание на move: замыкание забирает k к себе (иначе заём на локальную
//! переменную умер бы вместе с функцией).
//!
//! Заглушки уже возвращают замыкания-пустышки (голый todo!() в позиции impl Fn не
//! компилируется - компилятору нужен конкретный тип). Замените тела замыканий.

/// Возвращает функцию "прибавить k".
pub fn make_adder(k: i32) -> impl Fn(i32) -> i32 {
    move |_x| todo!("x + k")
}

/// Возвращает функцию "умножить на k".
pub fn make_scaler(k: i32) -> impl Fn(i32) -> i32 {
    move |_x| todo!("x * k")
}

/// Композиция: сначала f, потом g. (Дженерик с двумя параметрами-замыканиями.)
pub fn compose(
    f: impl Fn(i32) -> i32,
    g: impl Fn(i32) -> i32,
) -> impl Fn(i32) -> i32 {
    move |_x| todo!("g(f(x))")
}
