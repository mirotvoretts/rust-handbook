//! и тесты прошли. Код функций менять НЕ нужно.
//!
//! Подсказки:
//! - `duplicate` использует `p` дважды по значению -> `Point` должен быть `Copy`.
//! - `Label` владеет `String` (кучей) и поэтому НЕ может быть `Copy`. Но его можно `Clone`,
//!   а `clone_pair` этим пользуется.

// TODO: добавьте нужный derive, чтобы `duplicate` компилировался.
pub struct Point {
    pub x: i32,
    pub y: i32,
}

/// Возвращает две копии точки. Компилируется только если `Point: Copy`
/// (иначе `p` был бы moved-from после первого использования).
pub fn duplicate(p: Point) -> (Point, Point) {
    (p, p)
}

// TODO: добавьте нужный derive, чтобы `clone_pair` компилировался.
// ВНИМАНИЕ: `Copy` здесь добавить НЕЛЬЗЯ (тип владеет String). Разберитесь почему.
pub struct Label(pub String);

/// Возвращает две независимые копии метки через явный clone.
pub fn clone_pair(l: &Label) -> (Label, Label) {
    (l.clone(), l.clone())
}
