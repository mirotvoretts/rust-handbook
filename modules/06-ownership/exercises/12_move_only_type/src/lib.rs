//! 12 (3x) - Move-only тип: API, который нельзя использовать неправильно.
//!
//! `FileHandle` моделирует владение ресурсом (открытым файлом). Он НЕ должен быть ни `Copy`,
//! ни `Clone`: дубликат хендла позволил бы закрыть один и тот же файл дважды. Поэтому:
//!   - `open` создаёт хендл;
//!   - `descriptor`/`path` дают доступ по ссылке (`&self`), не отдавая владение;
//!   - `close` ПОТРЕБЛЯЕТ хендл (`self` по значению) и возвращает путь. После `close`
//!     переменная становится moved-from, и вызвать `close` повторно уже НЕ получится -
