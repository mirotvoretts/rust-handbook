//!   1. E0384 - переменной присваивают повторно, но она объявлена без `mut`;
//!   2. E0308 - тело функции заканчивается инструкцией с `;`, поэтому возвращает `()` вместо i32.
//!
//! Функция должна возвращать сумму чисел от 1 до n включительно (для n < 1 - 0).

pub fn sum_to(n: i32) -> i32 {
    let total = 0;
    let mut i = 1;
    while i <= n {
        total = total + i;
        i += 1;
    }
    total;
}
