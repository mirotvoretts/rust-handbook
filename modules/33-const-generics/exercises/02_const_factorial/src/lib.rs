//! 02 (0x) - const fn factorial и fib.
//!
//! Реализуй две `const fn`, пригодные и в константном контексте (в том числе как
//! размер массива), и в рантайме:
//! - `factorial(n: u64) -> u64` - факториал;
//! - `fib(n: u64) -> u64` - число Фибоначчи (`fib(0) = 0`, `fib(1) = 1`).
//!
//! Подсказки:
//! - в `const fn` нельзя использовать `for`/итераторы; циклы пиши через `while`;
//! - тело `todo!()` в `const fn` недопустимо, поэтому заглушка возвращает заведомо
//!   неверное значение - тесты падают на утверждениях, пока не решено.
//!
//! Про константные вычисления:
//! <https://doc.rust-lang.org/reference/const_eval.html>.
pub const fn factorial(n: u64) -> u64 {
    let _ = n;
    0
}

pub const fn fib(n: u64) -> u64 {
    let _ = n;
    0
}
