//! 07 (3x) - асинхронный TCP эхо-сервер на tokio.
//!
//! Асинхронный аналог упражнения M24-06. Сервер каждому клиенту возвращает ровно те
//! байты, что тот прислал, но обработка соединений - на async-задачах поверх рантайма
//! tokio, а не на потоках ОС. Требования к функции:
//! - привяжись к "127.0.0.1:0", узнай адрес и верни его вызывающему сразу, не
//!   дожидаясь клиентов;
//! - accept-цикл крути внутри рантайма tokio; каждое соединение обрабатывай отдельной
//!   задачей (tokio::spawn), читая всё до EOF и отправляя прочитанное обратно.
//!
//! Функция синхронная (возвращает SocketAddr), а async-мир живёт внутри рантайма.
//! Мост между ними придётся построить самому: подними рантайм tokio (например, на
//! своём потоке через std::thread::spawn), запусти в нём accept-цикл, а адрес верни
//! наружу (канал mpsc из M24 подойдёт). Клиенты в тестах - обычные синхронные сокеты,
//! так что сервер должен просто слушать бесконечно, пока жив процесс.
//!
//! Что понадобится (за пределами теории):
//! - учебник tokio (рантайм, spawn, async-сокеты): https://tokio.rs/tokio/tutorial
//! - async-сокеты: tokio::net::TcpListener / TcpStream
//!   https://docs.rs/tokio/latest/tokio/net/index.html
//! - async-чтение/запись: трейты AsyncReadExt / AsyncWriteExt (read_to_end, write_all)
//!   https://docs.rs/tokio/latest/tokio/io/index.html
//! - явное создание рантайма: tokio::runtime::Runtime (block_on)
//!   https://docs.rs/tokio/latest/tokio/runtime/struct.Runtime.html

