//! 03 (1x) - `unsafe fn` с контрактом и арифметикой указателей. Эталонное решение.

/// Сумма `len` подряд идущих `i64`, начиная с `ptr`.
///
/// # Safety
/// `ptr` должен быть валиден для чтения `len` последовательных значений `i64`:
/// одна аллокация, корректное выравнивание, инициализированные данные.
pub unsafe fn sum_raw(ptr: *const i64, len: usize) -> i64 {
    let mut sum = 0;
    for i in 0..len {
        // add(i) остаётся в пределах аллокации по контракту; чтение корректно.
        sum += unsafe { *ptr.add(i) };
    }
    sum
}
