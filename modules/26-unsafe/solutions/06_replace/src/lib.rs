//! 06 (2x) - `mem::replace` вручную через `ptr::read`/`write`. Эталонное решение.

use std::ptr;

pub fn replace<T>(slot: &mut T, new: T) -> T {
    unsafe {
        // read забирает прежнее значение по владению, не трогая память slot;
        let old = ptr::read(slot);
        // write кладёт new, НЕ дропая то, что там было (мы его уже забрали в old);
        ptr::write(slot, new);
        // old возвращаем - его дропнет вызывающий. Двойного дропа нет: исходную
        // ячейку мы больше не считаем инициализированной прежним значением.
        old
    }
}
