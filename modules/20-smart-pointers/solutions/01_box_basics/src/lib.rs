//! 01 (0x) - Box: значение на куче. Эталонное решение.
// В этом вводном упражнении Box намеренно берётся по значению ради демонстрации
// самого Box; в реальном коде clippy справедливо предложил бы обычный тип.
#![allow(clippy::boxed_local)]

/// Положить x в Box.
pub fn boxed(x: i32) -> Box<i32> {
    Box::new(x)
}

/// Разыменовать Box.
pub fn unbox(b: Box<i32>) -> i32 {
    *b
}

/// Сумма двух boxed-значений.
pub fn sum_boxed(a: Box<i32>, b: Box<i32>) -> i32 {
    *a + *b
}
