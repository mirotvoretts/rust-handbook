//! 08 (3x) - разбор потока записей type-length-value (раздел 6 README).
//!
//! TLV - распространённый способ упаковать переменное число записей разного размера в
//! один поток. Каждая запись:
//!
//!   1 байт : `typ`   - тип записи (произвольный `u8`);
//!   2 байта: `len`   - длина значения, `u16` big-endian;
//!   `len` байт: `value`.
//!
//! Записи идут вплотную, одна за другой, до конца буфера. Реализуй `parse_all`,
//! разбирающую весь `bytes` в `Vec<Tlv>`:
//! - пустой вход -> `Ok(vec![])`;
//! - на каждом шаге, если оставшихся байт не хватает на 3-байтовый заголовок или на
//!   объявленные `len` байт значения, вернуть `Err(TlvError::Truncated)`;
//! - иначе прочитать запись, сдвинуться на `3 + len` байт и продолжить, пока буфер не
//!   кончится ровно на границе записи.
//!
//! Ключевая сложность - вести позицию по буферу вручную и на каждом шаге проверять
//! границы ДО чтения (иначе индексирование запаникует). `len` читай через
//! `u16::from_be_bytes`, кусок среза приводи к массиву через `TryInto` (M13).

